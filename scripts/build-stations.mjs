// Regenerates StationData.js from the MTA's station dataset.
// Run by hand -- `node scripts/build-stations.mjs` -- and commit the output.
// Station names and routes change rarely; this is maintenance, not runtime.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const URL_ = "https://data.ny.gov/resource/39hk-dx4f.json?$limit=1000";
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "StationData.js");

const res = await fetch(URL_);
if (!res.ok) throw new Error(`station fetch failed: HTTP ${res.status}`);
const rows = await res.json();
if (rows.length !== 496) {
  console.warn(`WARNING: expected 496 stations, got ${rows.length}. ` +
    `The MTA may have opened or closed a station -- verify before committing.`);
}

const stations = rows
  .map((r) => ({
    id: r.gtfs_stop_id,
    name: r.stop_name,
    routes: (r.daytime_routes || "").split(/\s+/).filter(Boolean),
    borough: r.borough || "",
    line: r.line || "",
    complexId: r.complex_id || "",
    lat: Number(r.gtfs_latitude),
    lon: Number(r.gtfs_longitude),
    labelN: r.north_direction_label || "",
    labelS: r.south_direction_label || "",
  }))
  .sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

const body = stations
  .map((s) => "  " + JSON.stringify(s))
  .join(",\n");

writeFileSync(out, `// GENERATED by scripts/build-stations.mjs -- do not edit by hand.
// Source: ${URL_}
// Regenerate with: node scripts/build-stations.mjs
//
// Data only, no logic. Queries live in Stations.js so that regenerating this
// file can never clobber hand-written code.
//
// Child platform ids are NOT stored: all 496 parents have exactly the children
// {id+"N", id+"S"}, with no exceptions, so Stations.platformId derives them.

var STATIONS = [
${body}
]

if (typeof module !== "undefined") {
  module.exports = { STATIONS: STATIONS }
}
`);
console.log(`wrote ${out} with ${stations.length} stations`);
